"""Original RPC dispatch on bounded synthetic replies and pending state.

Executes MsgBuffer, protocol factory/readers, pending lookup/erase, std::function
invocation and the generated BY_ID receiver. The final application callback is
an observer, not Android/managed acceptance. RTTI, allocation, function-manager
ownership and libc/error boundaries are explicit substitutes. No sockets/game.
"""
from native_control import NativeControl,CTX,BUF,OUT,AUX,STOP

class ProtocolExceptionObserved(Exception):
    """Stop at original __cxa_throw; do not simulate C++ unwinding."""

def probe(library,body=None,pending=0x100000002,wire=None):
    if type(pending) is not int or not 0<=pending<2**64:
        raise ValueError('synthetic pending u64 required')
    if (body is None)==(wire is None):
        raise ValueError('supply exactly one synthetic body or wire')
    for value in (body,wire):
        if value is not None and (type(value) is not bytes or not 0<len(value)<=1024):
            raise ValueError('bounded synthetic bytes required')
    n=NativeControl(library)
    from unicorn import UC_HOOK_CODE
    visits=set();callbacks=[];heap=[AUX+0x4000];exception_types=[]
    watched={0x3abe34,0x399d90,0x3c3a24,0x3c180e,0x39c78c,0x3c1770,
             0x3c382c,0x3c34d8,0x3c2e70,0x36ace8,0x36c404,0x36a860}
    def trace(u,address,size,unused):
        if address in watched:visits.add(address)
    n.uc.hook_add(UC_HOOK_CODE,trace)
    def execute(entry,args,stubs):
        # NativeControl installs a per-execution hook. Remove it between stages;
        # retaining stale hooks would duplicate substituted runtime operations.
        original=n.uc.hook_add;handles=[]
        def add(*a,**k):
            handle=original(*a,**k);handles.append(handle);return handle
        n.uc.hook_add=add
        try:return n.execute(entry,args,stubs)
        finally:
            n.uc.hook_add=original
            for handle in handles:n.uc.hook_del(handle)
    transport_return=None
    if wire is not None:
        n.write(CTX+4,42);n.write(CTX+0x70c,65536);n.write(CTX+0x714,len(wire))
        n.uc.mem_write(BUF,wire)
        transport_return=execute(0x3abe34,(CTX,AUX,0),
                                {0x284fcc:('no socket/no further bytes',-3)})
        if transport_return:
            return {'transport_return':transport_return,'callbacks':[],'visits':sorted(visits)}
        length=n.read(AUX)
        if not 0<length<=1024:raise ValueError('decoded body size bound')
        body=bytes(n.uc.mem_read(OUT,length))
    # A synthetic caller hands transport output to the original RPC dispatcher;
    # connector queues, main-thread scheduling and real registration are absent.
    n.uc.mem_write(CTX,bytes(0xa0))
    msg=AUX+0x400;node=AUX+0x1000;function=node+0x18;holder=AUX+0x1400
    n.write(AUX+0x200,msg)
    n.write(msg,0x4f5780);n.write(msg+4,0x4f5420);n.write(msg+0x4c,AUX+0x1800)
    # Real libstdc++ one-node map layout, including header extrema/count/color.
    for offset in (0x58,0x5c,0x60):n.write(CTX+offset,node)
    n.write(CTX+0x64,1);n.write(node,1);n.write(node+4,CTX+0x54)
    n.write(node+0x10,pending,8)
    n.write(function,holder);n.write(function+8,STOP+0x301)
    n.write(function+0xc,0x36ace9)
    n.write(holder,0x36c405);n.write(holder+4,0)
    n.write(holder+8,123);n.write(holder+0x10,STOP+0x301)
    n.write(holder+0x14,STOP+0x201);n.write(holder+0x1c,AUX+0x1800)
    n.uc.mem_write(BUF,body)
    def allocate(size,*unused):
        if not 0<size<=8192:raise ValueError('allocation size bound')
        address=heap[0];heap[0]+=(size+15)&~15
        if heap[0]>=CTX+0x40000:raise ValueError('allocation total bound')
        return address
    def cast(pointer,*unused):
        if pointer!=msg:raise ValueError('unexpected RTTI object')
        return pointer
    def manager(dest,source,operation,*unused):
        if operation==2:n.uc.mem_write(dest,bytes(n.uc.mem_read(source,8)))
        elif operation!=3:raise ValueError('unexpected function-manager operation')
        return 0
    def signed(value):return value if value<2**31 else value-2**32
    def observe(function_data,status,result,*unused):
        begin=n.read(result+0xc);end=n.read(result+0x10)
        trees=(end-begin)//28 if end>=begin else -1
        value={'status':signed(status),'result':signed(n.read(result+4)),
               'trees':trees,'node_count':0,'node':b''}
        if trees==1:
            pointer=n.read(begin+8);length=n.read(pointer-12)
            if length>1024:raise ValueError('decoded synthetic node bound')
            value['node_count']=n.read(begin+4)
            value['node']=bytes(n.uc.mem_read(pointer,length))
        callbacks.append(value);return 0
    def throw(exception,*unused):
        exception_types.append(n.read(exception+8))
        raise ProtocolExceptionObserved()
    stubs={0x3c93fc:('bounded new',allocate),0x194160:('bounded malloc',allocate),
           0x194154:('free boundary',0),0x3c9bec:('delete boundary',0),
           0x193e00:('bounded strlen',lambda p,*_:len(bytes(n.uc.mem_read(p,1024)).split(b'\0',1)[0])),
           0x3c9b48:('validated RTTI boundary',cast),
           0x3c9ef8:('bounded exception allocation',allocate),
           0x3c9960:('observe native throw; no unwinding',throw),
           STOP+0x300:('functional synthetic function-manager',manager),
           STOP+0x200:('synthetic application callback observer',observe)}
    execute(0x399d90,(AUX+0x280,0,0x20,AUX+0x200),stubs)
    protocol=n.read(AUX+0x280)
    n.write(CTX+0x1c,protocol);n.write(CTX+0x20,n.read(AUX+0x284))
    flags=(n.read(protocol+0x20,1),n.read(protocol+0x21,1))
    result=None
    try:result=execute(0x3c3a24,(CTX,BUF,len(body)),stubs)
    except ProtocolExceptionObserved:pass
    return {'transport_return':transport_return,'dispatch_return':result,
            'callbacks':callbacks,'pending_count':n.read(CTX+0x64),
            'pending_root_empty':n.read(CTX+0x58)==0,'protocol_flags':flags,
            'native_exception_types':exception_types,'visits':sorted(visits),
            'runtime_boundaries':sorted(set(n.calls))}
